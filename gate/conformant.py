def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _base(public_url: str) -> str:
    return (public_url or "").rstrip("/")


def engine_requirements() -> dict[str, bool]:
    """What the shipped Gate engine already speaks. Attestation is not cert."""
    spend = spend_protocol_mod.spec("https://gate.local")
    fuse = license_fuse_mod.spec("https://gate.local")
    fail_closed = bool((spend.get("redeem") or {}).get("fail_closed"))
    children = bool(fuse.get("children_cannot_outlive_parent"))
    charge_only = bool((fuse.get("charge") or {}).get("not_admin_charge"))
    single_use = bool((spend.get("ticket") or {}).get("single_use"))
    return {
        "epoch_lock_persisted_until_charge_class_event": True,
        "single_use_server_redeem": single_use,
        "fail_closed_redeem": fail_closed,
        "override_impossibility_no_forged_resurrection": charge_only,
        "stranger_verify_receipt_without_operator_narration": True,
        "license_fuse_cascade_when_sublicensing": children,
        "annual_officer_attestation": False,
    }


def evaluate_claim(body: dict | None) -> dict[str, Any]:
    """Ghost Conformant = DENY. Selling may = DENY. Live cert waits on Gate 1."""
    claim = body if isinstance(body, dict) else {}
    sells_may = bool(
        claim.get("sells_may")
        or claim.get("admin_charge")
        or claim.get("grants_charge")
        or claim.get("sells_throat")
    )
    tests_passed = bool(claim.get("tests_passed"))
    attested = {str(x) for x in (claim.get("requirements") or [])}
    missing = [r for r in REQUIREMENTS if r not in attested]
    engine = engine_requirements()
    engine_ready = all(engine[r] for r in REQUIREMENTS if r != "annual_officer_attestation")

    if sells_may:
        return {
            "spec": SPEC,
            "verdict": "DENY",
            "reason": "never_sell_may",
            "certified": False,
            "ghost_conformant": False,
            "their_production": False,
            "mark": MARK,
        }
    if not tests_passed:
        return {
            "spec": SPEC,
            "verdict": "DENY",
            "reason": "ghost_conformant",
            "certified": False,
            "ghost_conformant": True,
            "missing_requirements": missing,
            "engine_ready": engine_ready,
            "their_production": False,
            "mark": MARK,
        }
    if missing:
        return {
            "spec": SPEC,
            "verdict": "DENY",
            "reason": "requirements_incomplete",
            "certified": False,
            "ghost_conformant": False,
            "missing_requirements": missing,
            "their_production": False,
            "mark": MARK,
        }
    return {
        "spec": SPEC,
        "verdict": "HOLD",
        "reason": "engine_conforms_cert_after_gate1",
        "certified": False,
        "ghost_conformant": False,
        "engine_ready": engine_ready,
        "their_production": False,
        "cash_usd": 0,
        "mark": MARK,
        "next": "stranger paid and proved",
    }


