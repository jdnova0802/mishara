def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _base(public_url: str) -> str:
    return (public_url or "").rstrip("/")


def _usd(n: int) -> str:
    return f"${int(n):,}"


def _decorate(row: dict[str, Any]) -> dict[str, Any]:
    out = dict(row)
    shape_usd = int(out.get("shape_usd") or 0)
    out["shape_usd"] = shape_usd
    out["shape_money"] = _usd(shape_usd)
    out["dunks_conformant_by"] = round(shape_usd / CONFORMANT_M1_USD, 2) if shape_usd else 0
    out["l2_module"] = L2_MODULE
    out["not_a_sibling"] = True
    out["until_gate1_usd"] = 0
    out["forecast"] = False
    return out


def inventions(*, horizon: str | None = None) -> list[dict[str, Any]]:
    rows = list(SOON) + list(MEDIUM) + list(LONG)
    if horizon:
        rows = [r for r in rows if r["horizon"] == horizon]
    return [_decorate(r) for r in rows]


